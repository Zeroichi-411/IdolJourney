export function generateName(rng: Rng, used: Set<string>): string {
  for (let i = 0; i < 200; i++) {
    const name = `${rng.pick(SURNAMES)} ${rng.pick(GIVEN_NAMES)}`;
    if (!used.has(name)) {
      used.add(name);
      return name;
    }
  }
  const fallback = `${rng.pick(SURNAMES)} ${rng.pick(GIVEN_NAMES)}${used.size}`;
  used.add(fallback);
  return fallback;
}

