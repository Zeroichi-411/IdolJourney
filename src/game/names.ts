export function generateSingleTitle(rng: Rng, used: Set<string>): string {
  for (let i = 0; i < 100; i++) {
    const t = rng.chance(0.3)
      ? rng.pick(TITLE_SOLO)
      : `${rng.pick(TITLE_A)}の${rng.pick(TITLE_B)}`;
    if (!used.has(t)) return t;
  }
  return `${rng.pick(TITLE_A)}の${rng.pick(TITLE_B)} ${used.size}`;
}
